#      逼着回去改**业务桶**（AI 复核单元那一步），而不是在现金流层糊过去。
#      ⚠️ 退款 / 退回也一样，不给反方向候选：退款说明桶判错了
#         （该进 单位往来 / 其他业务 之类），不是"收入的另一面"。
#   ② **无方向的桶两个方向都要列**。桶名只说"什么事"（税费、往来、借款、
#      长期资产、投资、利息），收付都可能；漏了反向项目，
