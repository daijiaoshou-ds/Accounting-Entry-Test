# 4. 兜底表：桶 + 方向 -> 挑不出来时的默认项目
#
# **只在"桶 + 方向有多个候选、一级科目裁判也挑不出来"时启用**（比裁判表更靠后）。
#
# 为什么需要它（利息收支的例子）：
#   利息收支 付现 有两个可能：偿付利息（筹资活动）、银行手续费（经营活动的
#   "支付其他…"）。一级科目能证成"是利息"（出现应付利息/应付股利），
#   但**证不成"是手续费"**——财务费用这个一级科目两者都有。
#   既然后者证不出来，就给它一个明确的默认值，而不是一律推给人工：
#   手续费是高频小额业务，全推人工等于把复核量放大。
#
# 维护约定：
#   * 只登记**证不成、且默认值几乎总是对**的组合
#   * 默认值必须是该桶该方向**已有的候选**（build 会校验，写错直接报错）
#   * 没登记的 = 仍然交人工复核（安全默认）
# ============================================================================
CF_FALLBACK = {
    "利息收支": {"付": "支付其他与经营活动有关的现金"},
}


def build() -> dict:
    """校验一致性，返回三份配置（不落盘）。"""
    bad = []
    for bkt, items in BUCKET_MAP.items():
        for it in items:
            if it not in CF_ITEMS:
                bad.append((bkt, it))
    if bad:
        raise ValueError(f"业务桶映射引用了不存在的现金流量项目: {bad}")

    sec_items = [x for v in CF_SECTIONS.values() for x in v]
    if sorted(sec_items) != sorted(CF_ITEMS):
        raise ValueError(
            "CF_ITEMS 与 CF_SECTIONS 不一致："
            f"仅分组有 {set(sec_items) - set(CF_ITEMS)}；"
            f"仅项目有 {set(CF_ITEMS) - set(sec_items)}")

    for item, subjects in ACCOUNT_RULING.items():
        if item not in CF_ITEMS:
            raise ValueError(f"裁判表引用了不存在的现金流量项目: {item}")
        if not subjects:
            raise ValueError(f"裁判表里「{item}」没有任何一级科目")

    # 裁判表只该登记"方向内真的会歧义"的项目，登记多余的说明它已经
    # 不歧义了（要么该删，要么说明桶映射改回去了），提醒一下
    ambiguous = _ambiguous_items()
    idle = sorted(set(ACCOUNT_RULING) - ambiguous)
    if idle:
        raise ValueError(
            f"裁判表里的项目现在并不歧义，应删除：{idle}。"
            f"（当前歧义项目：{sorted(ambiguous)}）")

    # 兜底表同理：登记的必须是"候选确实 >1"的组合，且默认值本身得是候选之一
    for bkt, per in CF_FALLBACK.items():
        if bkt not in BUCKET_MAP:
            raise ValueError(f"兜底表引用了不存在的业务桶: {bkt}")
        for d, item in per.items():
            if d not in ("收", "付"):
                raise ValueError(f"兜底表「{bkt}」的方向必须是 收/付，不是 {d}")
            cands = [i for i in BUCKET_MAP[bkt] if CF_ITEMS.get(i) == d]
            if len(cands) < 2:
                raise ValueError(
                    f"兜底表「{bkt}」[{d}] 只有一个候选（{cands}），"
                    f"不需要兜底，应删除")
            if item not in cands:
                raise ValueError(
                    f"兜底表「{bkt}」[{d}] 的默认值「{item}」不在候选里"
                    f"（候选：{cands}）")

    return {
        "cf_items": {
            "_comment": "24 个现金流量项目及其方向。方向是硬约束："
                        "映射表只给候选范围，方向由该笔货币资金科目"
                        "是借方还是贷方决定。",
            "items": CF_ITEMS,
            "sections": CF_SECTIONS,
        },
        "bucket_to_cf": {
            "_comment": "业务桶 -> 现金流量项目候选（无方向）。"
                        "空列表 = 不产生现金流量（折旧摊销非付现、"
                        "资金内部往来是货币资金互转）；"
                        "单向桶只列它那一个方向，反方向出现会落「待复核」；"
                        "汇兑损益挂「汇率变动对现金的影响」（中性项目）。",
            "map": BUCKET_MAP,
        },
        "account_ruling": {
            "_comment": "歧义裁判表 + 兜底表：都只在业务桶无法定出唯一项目时启用。"
                        "先用 ruling 拿一级科目当裁判；"
                        "裁判也挑不出来时才用 fallback 的默认值。"
                        "两者都没登记的 = 仍然交给人工复核。",
            "ruling": ACCOUNT_RULING,
            "fallback": CF_FALLBACK,
        },
    }


def _ambiguous_items() -> set:
    """哪些现金流量项目在"某个桶 + 某个方向"下会与其他项目并存。

    这些就是需要裁判的项目；其余项目永远由桶直接定出来。
    """
    out = set()
    for items in BUCKET_MAP.values():
        for d in ("收", "付"):
            cands = [i for i in items if CF_ITEMS.get(i) == d]
            if len(cands) > 1:
                out.update(cands)
    return out


def ambiguous_buckets() -> dict:
    """{桶: {"收": [...], "付": [...]}} —— 只列出真歧义的桶。"""
    out = {}
    for bkt, items in BUCKET_MAP.items():
        per = {}
        for d in ("收", "付"):
            cands = [i for i in items if CF_ITEMS.get(i) == d]
            if len(cands) > 1:
                per[d] = cands
        if per:
            out[bkt] = per
    return out


def check() -> dict:
    """只做校验，供自检用；失败时抛 ValueError。"""
    return build()


def main():
    data = build()
    CF_DIR.mkdir(parents=True, exist_ok=True)
    for stem, payload in data.items():
        p = CF_DIR / f"{stem}.json"
        p.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
        n = len(payload.get("map") or payload.get("items")
                or payload.get("ruling") or {})
        print(f"{p.name:22s} {n:4d} 条")

    empty = [b for b, v in BUCKET_MAP.items() if not v]
    print("不产生现金流的桶: " + (", ".join(empty) or "（无）"))

    neutral = [b for b, v in BUCKET_MAP.items()
               if v and any(CF_ITEMS.get(i) == "中性" for i in v)]
    if neutral:
        print("挂中性项目的桶（不归收付两侧）: " + ", ".join(neutral))

    amb = ambiguous_buckets()
    if amb:
        print("有歧义、需裁判表的桶:")
        for bkt, per in amb.items():
            for d, cands in per.items():
                tail = ""
                fb = CF_FALLBACK.get(bkt, {}).get(d)
                if fb:
                    tail = f"   兜底={fb}"
                print(f"  {bkt} [{d}现] -> " + " / ".join(cands) + tail)
    else:
        print("没有歧义桶")
    return 0


if __name__ == "__main__":
    sys.exit(main())
