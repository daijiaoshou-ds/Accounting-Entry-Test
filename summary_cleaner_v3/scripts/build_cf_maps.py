# 3. 歧义裁判表：一级科目 -> 现金流量项目
#
# **只在"业务桶无法定出唯一项目"时启用**，不参与正常判定。
# 依赖顺序严格是：业务桶定候选 → 方向筛 → 仍歧义才问一级科目。
#
# 为什么需要它：
#   「投资本金」收现方向既可能是"收回投资收到的现金"（投资活动）、
#   也可能是"吸收投资收到的现金"（筹资活动），还可能是
#   "取得投资收益收到的现金"（投资活动）。桶层面分不出，
#   因为根因是桶没拆开（股东投资 / 金融产品投资 / 投资收益）。
#   在还没重训模型之前，用一级科目当裁判：
#       交易性金融资产 / 长期股权投资 / 定期存款 … → 收回投资（投资活动）
#       实收资本 / 资本公积                        → 吸收投资（筹资活动）
#       投资收益 / 应收股利 / 应收利息              → 取得投资收益（投资活动）
#   ⚠️ 两类科目同时出现（赎回理财带收益：交易性金融资产 + 投资收益）
#      → 命中 2 个候选 → **待复核**。这是设计如此，不要"猜一个"。
#
# 维护约定：
#   * 只登记"真歧义"的项目，不要拿它当第二套主映射表
#   * 某条目标准确性没把握就**别登记** —— 登记了就会被自动采信；
#     漏登记只会退化成"待复核"，那是安全的默认
# ============================================================================
