def probe(title, rows, show_cols=("凭证号", "明细科目", "借方金额", "贷方金额", "客商名称")):
    df = pd.DataFrame(rows)
    out, stats = transform_journal_df(df, COL_MAP)
    print("=" * 78)
    print(title)
    print(f"  stats: {stats}")
    if out.empty:
        print("  <空>")
    else:
        print(out[list(show_cols)].to_string(index=False))
    return out, stats


